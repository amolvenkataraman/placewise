"""Names people type for places: datasets/names/aliases.json (CC BY 4.0, curated).

- `load` validates the dataset; `check_targets` checks every city against GeoNames cities1000 and
  `check_regions` every text against the curated regions' names.
- `render` writes `src/placewise/constants/countries/city_aliases.py`, the offline copy location
  search reads (regenerated by `python -m packbuild.cities`).
- `for_packs` gives the world pack's builder the aliases per GeoNames id and per country, and the
  GeoNames alternate names to drop.
"""

import json
import urllib.parse
from dataclasses import dataclass, field

from placewise.constants import countries
from placewise.constants._keys import city_key, key

from . import datasets
from .sources.geonames import GEONAME_FIELDS, read_admin1, read_tsv

DATASET = datasets.path("names", "aliases.json")  # in the placewise-data checkout (packbuild.datasets)
KINDS = ("code", "short", "colloquial", "former", "exonym", "name", "suppress")
READS_AS = ("city", "code")  # alone: the city first, or the code's own meaning (see the dataset)
FIELDS = {"text", "kind", "city", "country", "admin1", "geonames", "reads_as", "until", "source", "notes"}
CITED = ("code", "former")  # kinds that must cite a source
_F = {name: i for i, name in enumerate(GEONAME_FIELDS)}


def code_clashes(text):
    """Is `text` also an ISO 3166-1 code or a US, Canadian, UK or Indian subdivision code?"""
    k = key(text).upper()
    if not k.isalpha() or len(k) not in (2, 3):
        return False
    if (countries.BY_ALPHA2 if len(k) == 2 else countries.BY_ALPHA3).get(k) is not None:
        return True
    return any(k in table.BY_CODE for table in countries.SUBREGIONS.values())


def load(path=None):
    """Every entry of the dataset, validated, in file order."""
    path = path or DATASET
    entries = json.loads(path.read_text(encoding="utf-8"))["aliases"]
    seen = {}
    for entry in entries:
        _validate(entry)
        if entry["kind"] != "suppress":
            k = city_key(entry["text"])
            if k in seen:
                raise ValueError(f"{entry['text']!r}: listed twice (also as {seen[k]!r})")
            seen[k] = entry["text"]
    return entries


def _validate(e):
    where = repr(e.get("text"))
    if extra := set(e) - FIELDS:
        raise ValueError(f"{where}: unknown fields {sorted(extra)}")
    if not isinstance(e.get("text"), str) or not e["text"].strip() or "|" in e["text"]:
        raise ValueError(f"{where}: text must be a non-empty name without '|'")
    if e.get("kind") not in KINDS:
        raise ValueError(f"{where}: kind {e.get('kind')!r} is not one of {', '.join(KINDS)}")
    country = e.get("country")
    if country not in countries.BY_ALPHA2:
        raise ValueError(f"{where}: unknown country {country!r}")
    if "city" not in e:
        if e["kind"] != "former" or set(e) & {"admin1", "geonames"}:
            raise ValueError(f"{where}: names a city (city, geonames); only a former name may name a country")
    elif not isinstance(e.get("geonames"), int):
        raise ValueError(f"{where}: geonames must be the city's GeoNames id (a number)")
    table = countries.SUBREGIONS.get(country)
    if e.get("admin1") is not None and (table is None or e["admin1"] not in table.BY_CODE):
        raise ValueError(f"{where}: unknown admin1 {e['admin1']!r} for {country}")
    if e["kind"] in CITED and "source" not in e:
        raise ValueError(f"{where}: a {e['kind']} entry cites a source")
    if "source" in e:
        _check_source(where, e["source"])
    clash = e["kind"] != "suppress" and code_clashes(e["text"])
    if clash and e.get("reads_as") not in READS_AS:
        raise ValueError(f"{where}: is also an ISO or subdivision code: reads_as must be one of {READS_AS}")
    if not clash and "reads_as" in e:
        raise ValueError(f"{where}: reads_as is only for texts that are also codes")


def _check_source(where, source):
    url = urllib.parse.urlparse(str(source.get("url", ""))) if isinstance(source, dict) else None
    if url is None or set(source) != {"title", "url"} or not source["title"] or url.scheme != "https":
        raise ValueError(f"{where}: source must be {{title, url}} with an https:// url")


def check_regions(entries, regions):
    """A text that is also a region's name is allowed only for a principal city of that region
    (the city it is named after: "Bengaluru", "NYC")."""
    names = {}
    for r in regions:
        for name in (r["short_name"], r["name"], *r["aliases"]):
            names.setdefault(city_key(name), r)
    for e in entries:
        region = names.get(city_key(e["text"]))
        if region is None or e["kind"] == "suppress":
            continue
        cities = {city_key(c) for c in region.get("principal_cities", {})}
        if e.get("country") != region["country"] or city_key(e.get("city", "")) not in cities:
            raise ValueError(f"{e['text']!r} is also the name of {region['id']} ({region['short_name']})")


def check_targets(entries, cities_path, admin1_path):
    """Every city target is a GeoNames city with that name (or alternate name), country and admin1."""
    from .cities import _admin1  # the GeoNames admin1 -> ISO suffix rule the cities modules use

    wanted = {e["geonames"] for e in entries if "geonames" in e}
    rows = {}
    for row in read_tsv(cities_path, len(GEONAME_FIELDS)):
        if int(row[_F["geonameid"]]) in wanted:
            rows[int(row[_F["geonameid"]])] = row
    admin1_names = read_admin1(admin1_path)
    problems = []
    for e in entries:
        if "geonames" not in e:
            continue
        row = rows.get(e["geonames"])
        if row is None:
            problems.append(f"{e['text']}: no GeoNames city {e['geonames']}")
            continue
        names = {row[_F["name"]], row[_F["asciiname"]], *row[_F["alternatenames"]].split(",")}
        country = row[_F["country_code"]]
        if city_key(e["city"]) not in {city_key(n) for n in names if n}:
            problems.append(f"{e['text']}: {e['city']} is not a name of GeoNames {e['geonames']}")
        elif country != e["country"]:
            problems.append(f"{e['text']}: GeoNames {e['geonames']} is in {country}, not {e['country']}")
        elif e.get("admin1") and _admin1(country, row[_F["admin1_code"]], admin1_names) != e["admin1"]:
            problems.append(f"{e['text']}: GeoNames {e['geonames']} is not in {country}-{e['admin1']}")
    if problems:
        raise ValueError("aliases with wrong GeoNames targets: " + "; ".join(problems))


def render(entries):
    """The generated module's text."""
    city_items, country_items = [], []
    for e in entries:
        text = json.dumps(e["text"], ensure_ascii=False)
        if e["kind"] == "suppress":
            continue
        if "city" not in e:
            country_items.append(f"    {text}: {json.dumps(e['country'])},")
            continue
        admin1 = json.dumps(e["admin1"]) if e.get("admin1") else "None"
        extra = f', reads_as="{e["reads_as"]}"' if "reads_as" in e else ""
        city_items.append(
            f"    {text}: CityAlias({json.dumps(e['city'], ensure_ascii=False)}, {admin1}, "
            f'{json.dumps(e["country"])}, kind="{e["kind"]}"{extra}),'
        )
    cities_body, countries_body = "\n".join(city_items), "\n".join(country_items)
    return f'''"""GENERATED from datasets/names/aliases.json by packbuild.cities; do not edit.

Other names of cities (airport codes, short forms, nicknames, former names) -> the city's English
name, admin1 and country, with the kind of alias; and former names of countries -> alpha-2.
"""

from ._records import CityAlias

CITY_ALIASES = {{
{cities_body}
}}

COUNTRY_ALIASES = {{
{countries_body}
}}
'''


@dataclass
class PackAliases:
    """The curated aliases the world pack adds: (text, kind) per GeoNames city id and per country
    (alpha-2), the target's own name first; and per GeoNames id, the keys of names to drop."""

    cities: dict = field(default_factory=dict)
    countries: dict = field(default_factory=dict)
    suppressed: dict = field(default_factory=dict)


def for_packs(entries):
    out = PackAliases()
    for e in entries:
        if e["kind"] == "suppress":
            out.suppressed.setdefault(e["geonames"], set()).add(city_key(e["text"]))
            continue
        if "city" in e:
            names = out.cities.setdefault(e["geonames"], [(e["city"], "name")])
        else:
            names = out.countries.setdefault(e["country"], [])
        if city_key(e["text"]) not in {city_key(t) for t, _ in names}:
            names.append((e["text"], e["kind"]))
    return out
